import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const incidents=fs.readFileSync('assets/js/admin/incidents.js','utf8');
const requests=fs.readFileSync('assets/js/admin/requests.js','utf8');
const housing=fs.readFileSync('assets/js/admin/advanced.js','utf8');
const start=incidents.indexOf('const PARKING_SCORE_WEIGHTS=');
const end=incidents.indexOf('function parkingScorePanel(',start);
assert.ok(start>=0&&end>start,'Shared compliance score must exist');
const score=vm.runInNewContext(incidents.slice(start,end)+'\nparkingScore');
const now=Date.UTC(2026,10,20),recent=new Date(now-86400000).toISOString();
const row=(id,h,o,state,priority,attempts,action='')=>({ID_Incidencia:id,ID_Vivienda:h,ID_PropietarioAlHecho:o,FechaHora:recent,Estado:state,Prioridad:priority,Intentos:attempts,AccionCierre:action,Tipo:'QA'});
const rows=[row('a','h1','o1','Abierta','Normal',1),row('b','h1','o1','Abierta','Atención',3),row('c','h2','o1','Cerrada','Alta',2,'Aviso al propietario'),row('d','h1','o2','Cerrada','Normal',1,'Sin actuación')];
const home=rows.filter(x=>x.ID_Vivienda==='h1'),owner=rows.filter(x=>x.ID_PropietarioAlHecho==='o1');
assert.equal(score(home,{now}).score,88,'Open incidents and followups count');
assert.equal(score(owner,{now}).score,69,'Owner across two homes counts attributed history only');
assert.equal(score(home,{now,closeId:'a',action:'Aviso al propietario'}).score,85,'Closure simulation changes only chosen case');
assert.equal(score(home,{now,closeId:'a',action:'Sin actuación'}).score,91,'No-action closure clears provisional deduction');
assert.equal(score([...home,home[0]],{now}).score,88,'Duplicate incidents are not double counted');
const old={...row('old','h1','o1','Cerrada','Crítica',5,'Aviso al propietario'),FechaHora:'2024-01-01T00:00:00Z'};
assert.equal(score([old],{now}).score,100,'Expired history does not count');
const recovery={...row('recover','h1','o1','Cerrada','Alta',1,'Aviso al propietario'),FechaHora:new Date(now-95*86400000).toISOString()};
assert.equal(score([recovery],{now}).score,99,'Recovery after 90 days is capped by actual deduction');
assert.ok(requests.includes('parkingCompliancePanel(r,incidentRows,{ownerId:requestOwnerId(r)})'),'Request details must display compliance');
assert.ok(incidents.includes('parkingCompliancePanel(r,rows,{action:actionSel.value})'),'Closing incidents must preview score');
assert.ok(housing.includes('Puntuación vivienda')&&housing.includes('Puntuación propietario'),'Housing details must display both scores');
console.log('OK compliance: open/closed, followups, owner across homes, simulation, recovery and shared panels');
